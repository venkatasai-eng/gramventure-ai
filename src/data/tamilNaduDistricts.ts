/**
 * Look up a district by its canonical internal ID.
 */
export function getTamilNaduDistrictById(id: string): TamilNaduDistrict | undefined {
  return TAMIL_NADU_DISTRICTS.find((d) => d.id === id.toLowerCase().trim());
}

/**
 * Get localized display name for a district.
 */
export function getDistrictDisplayName(
  district: TamilNaduDistrict,
  language: 'en' | 'te' | 'ta'
): string {
  if (language === 'ta') return district.nameTa;
  if (language === 'te') return district.nameTe;
  return district.nameEn;
}
